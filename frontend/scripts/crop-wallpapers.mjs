// One-off: crop 10 tileable wallpapers out of the interior pack sheet.
// Usage (from frontend/): node scripts/crop-wallpapers.mjs [--preview out.png]
//
// Source: public/assets/interior full/basics/wallpapers.png (640x816, pixel art). The left columns
// are window frames; to the right, each row is one wallpaper design drawn as a strip of colour
// variants, with trim/moulding rows between designs. Each crop below takes one variant's pattern
// band only (no trim), and is one horizontal repeat wide, so it tiles left-right seamlessly.
// Stripe designs also repeat vertically, so their crop is a whole number of vertical periods;
// motif designs (roses, fruit, bunnies, stars, snow) are one wall-height band.
// Output: public/assets/wallpapers/wallpaper_01.png ... wallpaper_10.png (original pixels, no resampling).
import { mkdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

const SHEET = 'public/assets/interior full/basics/wallpapers.png';
const OUT = 'public/assets/wallpapers/';

// [file, name, x, y, width, height]
export const WALLPAPERS = [
  ['wallpaper_01', 'Sage Pinstripe', 160, 64, 16, 16],
  ['wallpaper_02', 'Navy Stripes', 192, 96, 16, 16],
  ['wallpaper_03', 'Butter Stripes', 144, 128, 16, 16],
  ['wallpaper_04', 'Walnut Panels', 336, 256, 16, 28],
  ['wallpaper_05', 'Blush Roses', 112, 320, 48, 20],
  ['wallpaper_06', 'Crimson Roses', 336, 320, 32, 26],
  ['wallpaper_07', 'Orange Grove', 208, 352, 48, 28],
  ['wallpaper_08', 'Bunny Moon', 304, 352, 16, 28],
  ['wallpaper_09', 'Snowflake Frost', 256, 448, 48, 28],
  ['wallpaper_10', 'Starry Night', 320, 480, 16, 27],
];

const { data, info } = await sharp(SHEET).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const px = (x, y) => data.readUInt32LE((y * info.width + x) * 4);
const sameRow = (a, b, x, w) => { for (let c = x; c < x + w; c++) if (px(c, a) !== px(c, b)) return false; return true; };

const args = process.argv.slice(2);
const previewPath = args.includes('--preview') ? args[args.indexOf('--preview') + 1] : null;
mkdirSync(OUT, { recursive: true });

const tiles = [];
for (const [file, name, x, y, w, h] of WALLPAPERS) {
  // Up-down: the row after the crop equals its first row for the stripe designs (exact repeat).
  // Left-right is checked visually in the tiled preview: neighbouring sheet columns are often
  // already a different colour variant, so a pixel test against them says nothing.
  const seamlessY = sameRow(y, y + h, x, w);
  const tile = sharp(SHEET).extract({ left: x, top: y, width: w, height: h });
  await tile.clone().png().toFile(`${OUT}${file}.png`);
  tiles.push({ file, name, w, h, buf: await tile.clone().png().toBuffer() });
  console.log(`${file}  ${name.padEnd(16)} (${x}, ${y}, ${w}x${h})  repeats up-down exactly: ${seamlessY ? 'yes' : 'no (one wall-height band)'}`);
}

// Frontend data module: tile size per wallpaper. The shop item id is wallpaper-<name>.
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
const rows = WALLPAPERS.map(([file, name, , , w, h]) =>
  `  ${JSON.stringify(`wallpaper-${slug(name)}`)}: { file: ${JSON.stringify(file)}, name: ${JSON.stringify(name)}, width: ${w}, height: ${h} },`);
writeFileSync('src/data/wallpapers.ts', [
  '// Generated by scripts/crop-wallpapers.mjs. Do not edit by hand; rerun the script instead.',
  '// Images: public/assets/wallpapers/<file>.png, one seamless tile each (pixel art, shown at whole-number scales).',
  'export interface WallpaperTile { file: string; name: string; width: number; height: number }',
  '',
  'export const WALLPAPERS: Record<string, WallpaperTile> = {',
  ...rows,
  '};',
  '',
  "export const wallpaperSrc = (tile: WallpaperTile) => `/assets/wallpapers/${tile.file}.png`;",
  '',
].join('\n'));

if (previewPath) {
  // Each wallpaper tiled over a 96x64 area at 3x, nearest-neighbour, with its id and name underneath.
  const S = 3, AW = 96, AH = 64, CW = AW * S + 24, CH = AH * S + 50, COLS = 5;
  const comps = [];
  for (const [i, t] of tiles.entries()) {
    const reps = [];
    for (let ty = 0; ty < AH; ty += t.h) for (let tx = 0; tx < AW; tx += t.w) reps.push({ input: t.buf, left: tx, top: ty });
    const area = await sharp({ create: { width: Math.ceil(AW / t.w) * t.w, height: Math.ceil(AH / t.h) * t.h, channels: 4, background: '#00000000' } })
      .composite(reps).png().toBuffer();
    const scaled = await sharp(area).extract({ left: 0, top: 0, width: AW, height: AH }).resize(AW * S, AH * S, { kernel: 'nearest' }).png().toBuffer();
    const cx = (i % COLS) * CW + 12, cy = Math.floor(i / COLS) * CH + 10;
    comps.push({ input: scaled, left: cx, top: cy });
    comps.push({ input: Buffer.from(`<svg width="${AW * S}" height="36"><text x="${AW * S / 2}" y="16" font-family="monospace" font-size="14" text-anchor="middle" fill="#2f2a20">${t.file}</text><text x="${AW * S / 2}" y="32" font-family="monospace" font-size="13" text-anchor="middle" fill="#6b5b3e">${t.name}</text></svg>`), left: cx, top: cy + AH * S + 4 });
  }
  await sharp({ create: { width: COLS * CW, height: Math.ceil(tiles.length / COLS) * CH + 10, channels: 4, background: '#f4f0e4' } }).composite(comps).png().toFile(previewPath);
  console.log(`Preview: ${previewPath}`);
}
